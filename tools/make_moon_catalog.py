"""Rebuild astro_id/moon_catalog.py from the IAU/USGS Gazetteer of Planetary Nomenclature (public domain).

    curl -L -o moon.zip https://asc-planetarynames-data.s3.us-west-2.amazonaws.com/MOON_nomenclature_center_pts.zip
    # unzip it into its own empty folder, then:
    uv run python tools/make_moon_catalog.py <folder>/MOON_nomenclature_center_pts.dbf

The curated list (which names) is below; positions and diameters come from the gazetteer. The Apollo landing sites
are not gazetteer entries; their coordinates are NASA NSSDCA values (public domain), written as given below.
"""
from __future__ import annotations

import struct
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "astro_id" / "moon_catalog.py"

MARIA = ["Oceanus Procellarum", "Mare Imbrium", "Mare Serenitatis", "Mare Tranquillitatis", "Mare Crisium",
         "Mare Fecunditatis", "Mare Nectaris", "Mare Nubium", "Mare Humorum", "Mare Cognitum", "Mare Insularum",
         "Mare Vaporum", "Mare Frigoris", "Mare Smythii", "Mare Marginis", "Mare Undarum", "Mare Spumans",
         "Mare Humboldtianum", "Mare Australe", "Mare Orientale", "Sinus Iridum", "Sinus Medii", "Sinus Aestuum",
         "Sinus Roris", "Palus Epidemiarum", "Palus Putredinis", "Lacus Somniorum", "Lacus Mortis"]
MOUNTAINS = ["Montes Apenninus", "Montes Alpes", "Montes Caucasus", "Montes Carpatus", "Montes Haemus",
             "Montes Jura", "Montes Pyrenaeus", "Montes Riphaeus", "Montes Taurus", "Montes Teneriffe"]
CRATERS = ["Tycho", "Copernicus", "Kepler", "Aristarchus", "Plato", "Clavius", "Grimaldi", "Ptolemaeus",
           "Alphonsus", "Arzachel", "Theophilus", "Cyrillus", "Catharina", "Petavius", "Langrenus", "Gassendi",
           "Schickard", "Archimedes", "Eratosthenes", "Posidonius", "Aristoteles", "Eudoxus", "Atlas", "Hercules",
           "Maginus", "Longomontanus", "Bailly", "Deslandres", "Janssen", "Hipparchus", "Albategnius", "Walther",
           "Purbach", "Stöfler", "Maurolycus", "Furnerius", "Vendelinus", "Cleomedes", "Endymion", "Proclus",
           "Manilius", "Menelaus", "Bullialdus", "Pythagoras", "Schiller", "Fracastorius", "Messier", "Hevelius"]
# Lunar Module positions (lat N, lon E) from NASA NSSDCA, https://nssdc.gsfc.nasa.gov/planetary/lunar/lunar_sites.html
# (LRO images, Wagner et al. 2017, Icarus 283, 92-103; mean Earth/polar axis frame).
APOLLO = [("Apollo 11", 0.67416, 23.47314), ("Apollo 12", -3.0128, -23.4219), ("Apollo 14", -3.64589, -17.47194),
          ("Apollo 15", 26.13239, 3.63330), ("Apollo 16", -8.9734, 15.5011), ("Apollo 17", 20.1911, 30.7723)]


def read_dbf(path: Path) -> list[dict]:
    raw = path.read_bytes()
    n, hlen, rlen = struct.unpack("<IHH", raw[4:12])
    fields, off = [], 32
    while raw[off] != 0x0D:
        fd = raw[off:off + 32]
        fields.append((fd[:11].split(b"\0")[0].decode(), fd[16]))
        off += 32
    rows = []
    for i in range(n):
        rec = raw[hlen + i * rlen: hlen + (i + 1) * rlen]
        if rec[:1] == b"*":
            continue
        pos, row = 1, {}
        for name, ln in fields:
            row[name] = rec[pos:pos + ln].decode("utf-8", "replace").strip()
            pos += ln
        rows.append(row)
    return rows


def main(dbf: str) -> int:
    rows = read_dbf(Path(dbf))
    by = {}
    for r in rows:
        by.setdefault(r["name"], r)
        by.setdefault(r["clean_name"], r)
    out = []
    for kind, names in (("mare", MARIA), ("mountains", MOUNTAINS), ("crater", CRATERS)):
        for nm in names:
            r = by.get(nm)
            if r is None:
                print(f"not in the gazetteer: {nm}", file=sys.stderr)
                return 1
            lon = float(r["center_lon"])
            lon = lon - 360.0 if lon > 180.0 else lon
            out.append((nm, kind, round(float(r["center_lat"]), 2), round(lon, 2), round(float(r["diameter"]))))
    out += [(nm, "landing site", round(la, 3), round(lo, 3), 0) for nm, la, lo in APOLLO]
    lines = ['"""Curated lunar features: (name, kind, lat deg N, lon deg E, diameter km).',
             "",
             "Names, centres and diameters: IAU WGPSN / USGS Astrogeology, Gazetteer of Planetary Nomenclature",
             "(MOON_nomenclature_center_pts, public domain). Apollo sites: NASA NSSDCA (public domain), size 0.",
             'Generated by tools/make_moon_catalog.py; do not edit by hand."""',
             "",
             "FEATURES: tuple[tuple[str, str, float, float, int], ...] = ("]
    lines += [f"    ({nm!r}, {k!r}, {la}, {lo}, {d})," for nm, k, la, lo, d in out]
    lines.append(")")
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"{len(out)} features -> {OUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1]))
